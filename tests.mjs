import {createRequire} from "node:module";
import assert from "node:assert/strict";
const require=createRequire(import.meta.url);
const C=require("./core.js");
const cycle=C.presets()["14-14"].cycle;
const data={anchor:"2026-08-04",cycle,overrides:{},leaves:[]};
assert.equal(C.primaryEvent(data,"2026-08-04").type,"day");
assert.equal(C.primaryEvent(data,"2026-08-17").type,"day");
assert.equal(C.primaryEvent(data,"2026-08-18").type,"off");
assert.equal(C.primaryEvent(data,"2026-08-31").type,"off");
assert.equal(C.primaryEvent(data,"2026-09-01").type,"day");
assert.equal(C.primaryEvent(data,"2026-07-21").type,"off");
const muscat="Asia/Muscat";
const night={type:"night",start:"19:00",end:"07:00"};
const it=C.interval("2026-08-28",night,muscat);
assert.equal((it.end-it.start)/3600000,12);
const mixed={anchor:"2026-08-01",cycle:C.presets()["2d2n4"].cycle,overrides:{},leaves:[]};
assert.equal(C.primaryEvent(mixed,"2026-08-03").type,"night");
assert.equal(C.primaryEvent(mixed,"2026-08-05").type,"off");
mixed.overrides["2026-08-05"]={type:"overtime",start:"08:00",end:"12:00"};
assert.equal(C.primaryEvent(mixed,"2026-08-05").type,"overtime");
mixed.leaves=[{type:"annual",start:"2026-08-01",end:"2026-08-02"}];
assert.equal(C.primaryEvent(mixed,"2026-08-01").type,"annual");
assert.equal(C.annualLeaveUsed(mixed,2026,false),2);
const block=C.restBlock(data,"2026-08-10",false);
assert.deepEqual({start:block.start,end:block.end,returnDate:block.returnDate,length:block.length},{start:"2026-08-18",end:"2026-08-31",returnDate:"2026-09-01",length:14});
const stats=C.monthStats(data,2026,8,12);
assert.deepEqual({work:stats.workDays,off:stats.offDays,hours:stats.hours},{work:14,off:17,hours:168});
console.log("Dawami core: all tests passed");